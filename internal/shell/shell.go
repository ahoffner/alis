// Package shell renders the code `alis init` emits for zsh and bash.
//
// The output must never write to the terminal when evaluated: zsh plugins like
// Powerlevel10k's instant prompt treat any console output during startup as an error.
package shell

import (
	"fmt"
	"io"
	"strings"

	"github.com/ahoffner/alis/internal/manifest"
)

// Shell is a supported shell dialect.
type Shell string

const (
	Zsh  Shell = "zsh"
	Bash Shell = "bash"
)

// Parse validates a shell name.
func Parse(name string) (Shell, error) {
	switch Shell(name) {
	case Zsh, Bash:
		return Shell(name), nil
	}
	return "", fmt.Errorf("unsupported shell %q (supported: zsh, bash)", name)
}

// Quote single-quotes s for either shell.
func Quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// Init writes the integration script for sh.
//
// Shells expand aliases when a function is defined, not when it runs, and zsh parses an
// entire eval'd string before running any of it. So the functions go in a nested eval that
// is only parsed after the aliases exist, letting a function body use another command's alias.
func Init(w io.Writer, sh Shell, cmds []*manifest.Command, libFile string) error {
	var b strings.Builder
	b.WriteString("# Generated by `alis init " + string(sh) + "`. Do not edit; change your packs instead.\n")

	names := make([]string, 0, len(cmds))
	for _, c := range cmds {
		names = append(names, c.Name)
	}
	writeCleanup(&b, sh, names)

	if libFile != "" {
		b.WriteString("export ALIS_LIB=" + Quote(libFile) + "\n")
	}
	for _, c := range cmds {
		if c.Kind() == manifest.KindAlias {
			fmt.Fprintf(&b, "alias %s=%s\n", c.Name, Quote(c.Alias))
		}
	}
	// Each definition gets its own silenced eval, so a function body with a syntax error is
	// skipped (and reported by `alis doctor`) instead of printing during shell startup.
	// `function name {` plus the unalias stops the shell expanding an existing alias of the
	// same name (e.g. oh-my-zsh's `gc`) while parsing the definition.
	for _, c := range cmds {
		switch c.Kind() {
		case manifest.KindFunction:
			writeEval(&b, fmt.Sprintf("unalias %s 2>/dev/null\nfunction %s {\n%s\n}", c.Name, c.Name, strings.TrimRight(c.Function, "\n")))
		case manifest.KindScript:
			writeEval(&b, fmt.Sprintf("unalias %s 2>/dev/null\nfunction %s { %s \"$@\"; }", c.Name, c.Name, Quote(c.ScriptPath())))
		}
	}
	writeEval(&b, "unalias alis 2>/dev/null\n"+strings.TrimRight(wrapper[sh], "\n"))

	_, err := io.WriteString(w, b.String())
	return err
}

func writeEval(b *strings.Builder, code string) {
	b.WriteString("eval " + Quote(code) + " 2>/dev/null\n")
}

// FunctionSource is a standalone definition of a function command, for syntax checking.
func FunctionSource(c *manifest.Command) string {
	return fmt.Sprintf("function %s {\n%s\n}\n", c.Name, strings.TrimRight(c.Function, "\n"))
}

// writeCleanup removes whatever a previous `alis init` defined, so re-running init after
// removing or disabling a command doesn't leave it behind, then records the new names.
func writeCleanup(b *strings.Builder, sh Shell, names []string) {
	list := strings.Join(names, " ")
	switch sh {
	case Zsh:
		b.WriteString(`if (( ${+__alis_names} )); then
  for __alis_n in $__alis_names; do unalias $__alis_n 2>/dev/null; unfunction $__alis_n 2>/dev/null; done
  unset __alis_n
fi
typeset -ga __alis_names
__alis_names=(` + list + ")\n")
	case Bash:
		b.WriteString(`if [ -n "${__alis_names+x}" ]; then
  for __alis_n in "${__alis_names[@]}"; do unalias "$__alis_n" 2>/dev/null; unset -f "$__alis_n" 2>/dev/null; done
  unset __alis_n
fi
__alis_names=(` + list + ")\n")
	}
}

// wrapper is the `alis` shell function. With no arguments it opens the picker and puts the
// chosen command on your prompt; after commands that change packs it reloads the integration.
var wrapper = map[Shell]string{
	Zsh: `function alis {
  if (( $# == 0 )); then
    local __alis_cmd
    __alis_cmd="$(command alis pick)" || return
    [[ -n $__alis_cmd ]] && print -z -- "$__alis_cmd"
    return 0
  fi
  command alis "$@" || return
  case "$1" in
    pack|enable|disable|local|update) eval "$(command alis init zsh)" ;;
  esac
}
`,
	Bash: `function alis {
  if [ $# -eq 0 ]; then
    local __alis_cmd
    __alis_cmd="$(command alis pick)" || return
    if [ -n "$__alis_cmd" ]; then
      history -s -- "$__alis_cmd"
      printf '%s\n' "$__alis_cmd   (press ↑ to edit and run)"
    fi
    return 0
  fi
  command alis "$@" || return
  case "$1" in
    pack|enable|disable|local|update) eval "$(command alis init bash)" ;;
  esac
}
`,
}
